-- ForeverDB PUBLIC READ MODEL 0003: publication operations (additive; requires 0001).
--
-- Target: the isolated public-read database only (azerdex-public-read). Adds, and changes nothing that exists:
--   pub.publish_runs        bounded run log (ring buffer, one row per publisher run: outcome, timings, counts, error CLASS)
--   pub.publisher_lease     single-row lease so Cron and manual runs can never overlap
--   pub_admin.acquire_lease / release_lease / record_run / ops_status
-- No table privileges are granted to any login; the publisher reaches these only through the SECURITY DEFINER
-- functions below, exactly like the rest of pub_admin. The website reader gets nothing.
--
-- It also lets the migration owner (Supabase `postgres`) assume the publisher role with SET ROLE (no inheritance),
-- which is how the Edge Function writes: the connection is the project's own database login, every statement runs as
-- `foreverdb_publisher` (SET LOCAL ROLE inside the transaction), so RLS and grants of that role apply and
-- `postgres`-level privileges are never used for publication writes.
begin;

grant foreverdb_pub_owner to current_user with set true, inherit false;
grant foreverdb_publisher to current_user with set true, inherit false;
set local role foreverdb_pub_owner;

-- Bounded ring buffer (2000 slots, ~3 weeks at one run per 15 minutes): a new run overwrites the oldest slot (upsert), so
-- the log never grows and no row is ever deleted.
create table pub.publish_runs (
    id bigint generated by default as identity primary key,
    slot integer not null unique check (slot between 0 and 1999),
    started_at timestamptz not null,
    finished_at timestamptz not null default now(),
    trigger text not null check (trigger in ('cron', 'manual', 'cli', 'benchmark')),
    mode text not null check (mode in ('publish', 'dry_run', 'rehearse')),
    outcome text not null check (outcome in ('activated', 'duplicate', 'skipped_busy', 'failed', 'dry_run_ok', 'rehearsal_ok')),
    publication_id bigint,            -- no FK: retired publications are pruned, the log must survive
    error_class text check (error_class is null or length(error_class) <= 80),
    error_detail jsonb check (error_detail is null or pg_column_size(error_detail) <= 4096),
    worker_version text not null check (length(worker_version) between 1 and 40),
    source_data_updated_at timestamptz,
    content_sha256 text check (content_sha256 is null or content_sha256 ~ '^[0-9a-f]{64}$'),
    metrics jsonb not null default '{}'::jsonb check (pg_column_size(metrics) <= 8192)
);
create index publish_runs_finished_idx on pub.publish_runs (finished_at desc);
create index publish_runs_outcome_idx on pub.publish_runs (outcome, finished_at desc);
alter table pub.publish_runs enable row level security;

create table pub.publisher_lease (
    id smallint primary key default 1 check (id = 1),
    holder text,
    acquired_at timestamptz,
    expires_at timestamptz not null default '-infinity'
);
insert into pub.publisher_lease (id) values (1);
alter table pub.publisher_lease enable row level security;

-- Lease: refused while another holder's lease is unexpired. A crashed run frees itself at expiry (TTL).
create function pub_admin.acquire_lease(p_holder text, p_ttl_seconds integer)
returns boolean language plpgsql security definer set search_path = ''
as $$
declare v_got integer;
begin
    if p_holder is null or length(p_holder) not between 1 and 80 or p_ttl_seconds is null or p_ttl_seconds not between 30 and 900 then
        raise exception 'invalid lease request';
    end if;
    update pub.publisher_lease
       set holder = p_holder, acquired_at = now(), expires_at = now() + make_interval(secs => p_ttl_seconds)
     where id = 1 and expires_at < now();
    get diagnostics v_got = row_count;
    return v_got = 1;
end;
$$;

create function pub_admin.release_lease(p_holder text)
returns void language plpgsql security definer set search_path = ''
as $$
begin
    update pub.publisher_lease set expires_at = '-infinity' where id = 1 and holder = p_holder;
end;
$$;

-- Run log writer (ring buffer). Inputs are validated by the table constraints; callers pass reason CODES only.
create function pub_admin.record_run(
    p_trigger text, p_mode text, p_outcome text, p_publication_id bigint,
    p_error_class text, p_error_detail jsonb, p_worker_version text,
    p_started_at timestamptz, p_source_data_updated_at timestamptz, p_content_sha256 text, p_metrics jsonb
)
returns bigint language plpgsql security definer set search_path = ''
as $$
declare v_id bigint := nextval('pub.publish_runs_id_seq');
begin
    insert into pub.publish_runs (id, slot, started_at, finished_at, trigger, mode, outcome, publication_id, error_class,
                                  error_detail, worker_version, source_data_updated_at, content_sha256, metrics)
    values (v_id, (v_id % 2000)::integer, p_started_at, now(), p_trigger, p_mode, p_outcome, p_publication_id, p_error_class,
            p_error_detail, p_worker_version, p_source_data_updated_at, p_content_sha256, coalesce(p_metrics, '{}'::jsonb))
    on conflict (slot) do update
       set id = excluded.id, started_at = excluded.started_at, finished_at = excluded.finished_at, trigger = excluded.trigger,
           mode = excluded.mode, outcome = excluded.outcome, publication_id = excluded.publication_id,
           error_class = excluded.error_class, error_detail = excluded.error_detail, worker_version = excluded.worker_version,
           source_data_updated_at = excluded.source_data_updated_at, content_sha256 = excluded.content_sha256,
           metrics = excluded.metrics;
    return v_id;
end;
$$;

-- One-call operational view (owner/operator and the publisher). `stale` means no successful publish/duplicate-check
-- (a real run that read the source and confirmed the public data matches it) within p_stale_after_seconds.
create function pub_admin.ops_status(p_stale_after_seconds integer default 2700)
returns jsonb language sql stable security definer set search_path = ''
as $$
    with st as (select active_publication_id as active from pub.state where id = 1),
    ap as (select p.* from pub.publications p join st on p.id = st.active),
    ok_run as (
        select * from pub.publish_runs where mode = 'publish' and outcome in ('activated', 'duplicate')
        order by finished_at desc limit 1),
    last_run as (select * from pub.publish_runs where mode = 'publish' order by finished_at desc limit 1),
    last_fail as (select * from pub.publish_runs where outcome = 'failed' order by finished_at desc limit 1),
    last_act as (select * from pub.publish_runs where outcome = 'activated' and mode = 'publish' order by finished_at desc limit 1)
    select jsonb_build_object(
        'activePublicationId', (select active from st),
        'activatedAt', (select activated_at from ap),
        'sourceDataUpdatedAt', (select source_data_updated_at from ap),
        'sourceExportedAt', (select source_exported_at from ap),
        'contentSha256', (select content_sha256 from ap),
        'counts', (select jsonb_build_object(
            'sources', counts->'sources', 'items', counts->'items', 'zones', counts->'zones',
            'publishedLocationCells', counts->'locations', 'drops', counts->'drops', 'buckets', counts->'buckets') from ap),
        'previousAvailableForRollback', exists (
            select 1 from pub.publications p, st where p.status = 'retired' and p.content_sha256 is not null and p.id <> st.active),
        'retainedPublicationIds', coalesce((select jsonb_agg(id order by id desc) from pub.publications where content_sha256 is not null), '[]'::jsonb),
        'lastRun', (select jsonb_build_object('id', id, 'outcome', outcome, 'trigger', trigger, 'finishedAt', finished_at,
                                              'durationMs', metrics->'totalMs', 'errorClass', error_class) from last_run),
        'lastSuccessfulRun', (select jsonb_build_object('id', id, 'outcome', outcome, 'finishedAt', finished_at,
                                              'durationMs', metrics->'totalMs') from ok_run),
        'lastActivation', (select jsonb_build_object('id', id, 'publicationId', publication_id, 'finishedAt', finished_at,
                                              'durationMs', metrics->'totalMs') from last_act),
        'lastPublishDurationMs', (select metrics->'totalMs' from last_run),
        'lastError', (select jsonb_build_object('runId', id, 'at', finished_at, 'mode', mode, 'errorClass', error_class, 'detail', error_detail) from last_fail),
        'lastSuccessAgeSeconds', (select extract(epoch from (now() - finished_at))::bigint from ok_run),
        'lease', (select jsonb_build_object('heldNow', expires_at > now(), 'acquiredAt', acquired_at,
                      'expiresAt', case when expires_at = '-infinity' then null else expires_at end,
                      -- expired but never released: the run that held it was killed (e.g. platform CPU/wall limit) before it could clean up
                      'abandoned', (expires_at <> '-infinity' and expires_at <= now())) from pub.publisher_lease where id = 1),
        'staleAfterSeconds', p_stale_after_seconds,
        'stale', coalesce((select now() - finished_at > make_interval(secs => p_stale_after_seconds) from ok_run), true),
        'runsLast24h', (select jsonb_build_object(
            'total', count(*), 'activated', count(*) filter (where outcome = 'activated'),
            'duplicate', count(*) filter (where outcome = 'duplicate'), 'skippedBusy', count(*) filter (where outcome = 'skipped_busy'),
            'failed', count(*) filter (where outcome = 'failed'))
            from pub.publish_runs where mode = 'publish' and finished_at > now() - interval '24 hours')
    );
$$;

revoke all on all functions in schema pub_admin from public;
grant execute on function pub_admin.acquire_lease(text, integer) to foreverdb_publisher;
grant execute on function pub_admin.release_lease(text) to foreverdb_publisher;
grant execute on function pub_admin.record_run(text, text, text, bigint, text, jsonb, text, timestamptz, timestamptz, text, jsonb) to foreverdb_publisher;
grant execute on function pub_admin.ops_status(integer) to foreverdb_publisher;
-- activate_publication (rollback) remains an operator action: not granted to anyone.

do $timeouts$
declare f regprocedure;
begin
    for f in select p.oid::regprocedure from pg_proc p join pg_namespace n on n.oid = p.pronamespace
             where n.nspname = 'pub_admin' and p.proname in ('acquire_lease', 'release_lease', 'record_run', 'ops_status') loop
        execute format('alter function %s set statement_timeout = ''5s''', f);
    end loop;
end
$timeouts$;

-- Boundary assertions (run as the owner): abort if any login gained a table privilege or the web reader gained anything.
do $verify$
declare t text;
begin
    foreach t in array array['publish_runs', 'publisher_lease'] loop
        if has_table_privilege('foreverdb_web_reader', format('pub.%I', t), 'select')
           or has_table_privilege('foreverdb_publisher', format('pub.%I', t), 'select')
           or has_table_privilege('foreverdb_publisher', format('pub.%I', t), 'insert')
           or has_table_privilege('foreverdb_publisher', format('pub.%I', t), 'update')
           or has_table_privilege('foreverdb_publisher', format('pub.%I', t), 'delete') then
            raise exception 'Operations boundary FAILED for pub.%', t;
        end if;
    end loop;
    if has_function_privilege('foreverdb_web_reader', 'pub_admin.record_run(text, text, text, bigint, text, jsonb, text, timestamptz, timestamptz, text, jsonb)', 'execute')
       or has_function_privilege('foreverdb_web_reader', 'pub_admin.ops_status(integer)', 'execute')
       or has_function_privilege('foreverdb_publisher', 'pub_admin.activate_publication(bigint)', 'execute') then
        raise exception 'Operations role separation FAILED';
    end if;
end
$verify$;

reset role;
commit;

