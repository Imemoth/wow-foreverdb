#!/usr/bin/env node
// Generates supabase/functions/azerdex-welcome-worker/logo-data.ts from azerdex-logo.png (the reviewed, sha256-pinned source asset).
// Why embed: Supabase cannot ship static files with API-based deploys (dashboard / MCP / `--use-api`), only with CLI+Docker deploys. A module that is
// part of the import graph is bundled by every deploy path, so the emblem can never be "missing" in a deployed function.
//   node scripts/embed-azerdex-logo.mjs          write the module
//   node scripts/embed-azerdex-logo.mjs --check  exit 1 if the committed module is stale (used by the test suite)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";

const dir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../supabase/functions/azerdex-welcome-worker");
// Other functions that attach the same emblem get their own generated copy (API-based deploys bundle only the function's own directory).
const COPIES = [path.resolve(dir, "../azerdex-auth-email/logo-data.ts")];
export function render() {
  const png = fs.readFileSync(path.join(dir, "azerdex-logo.png"));
  const sha = createHash("sha256").update(png).digest("hex");
  return `// GENERATED by scripts/embed-azerdex-logo.mjs from azerdex-logo.png. Do not edit by hand: tests/welcome-worker/asset-and-deno.test.mjs fails if stale.
// ${png.length} bytes, sha256 ${sha}
export const LOGO_PNG_SHA256 = "${sha}";
export const LOGO_PNG_BASE64 =
  "${png.toString("base64")}";
`;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = path.join(dir, "logo-data.ts");
  if (process.argv.includes("--check")) {
    const ok = [out, ...COPIES].every((f) => fs.existsSync(f) && fs.readFileSync(f, "utf8") === render());
    console.log(ok ? "logo-data.ts is up to date" : "logo-data.ts is STALE: run node scripts/embed-azerdex-logo.mjs");
    process.exit(ok ? 0 : 1);
  }
  for (const f of [out, ...COPIES]) {
    fs.writeFileSync(f, render());
    console.log(`wrote ${path.relative(process.cwd(), f)}`);
  }
}
