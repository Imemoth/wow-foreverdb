#!/usr/bin/env node
/**
 * Keeps the Edge Function's copy of the publication core byte-identical to publisher/src/core.
 *
 *   node scripts/sync-edge-core.mjs          write the copy (and the generated config module)
 *   node scripts/sync-edge-core.mjs --check  exit 1 when the committed copy is out of date (run by the publisher tests/CI)
 *
 * The Supabase MCP/API deploy takes a flat list of files, so shared code is copied into the function directory
 * instead of imported across directories. publisher/src/core stays the ONLY place the business logic is edited.
 */
import { copyFileSync, mkdirSync, readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = join(root, "publisher/src/core");
const outDir = join(root, "supabase/functions/publish-observations");
const check = process.argv.includes("--check");

const expected = new Map();
for (const f of readdirSync(srcDir).filter((n) => n.endsWith(".ts")).sort()) {
  expected.set(join("core", f), readFileSync(join(srcDir, f), "utf8"));
}
const cfg = JSON.parse(readFileSync(join(root, "publisher/publication-config.json"), "utf8"));
expected.set(
  "publication-config.generated.ts",
  `// GENERATED by scripts/sync-edge-core.mjs from publisher/publication-config.json. Do not edit.\nexport default ${JSON.stringify(cfg, null, 2)};\n`,
);

let drift = [];
for (const [rel, content] of expected) {
  const target = join(outDir, rel);
  const current = existsSync(target) ? readFileSync(target, "utf8") : null;
  if (current === content) continue;
  drift.push(rel);
  if (!check) {
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, content);
  }
}
if (check && drift.length) {
  console.error(`Edge Function copy is out of date: ${drift.join(", ")}\nRun: node scripts/sync-edge-core.mjs`);
  process.exit(1);
}
console.log(check ? "edge core in sync" : drift.length ? `updated: ${drift.join(", ")}` : "edge core already in sync");
